"""Generate the small, standalone protocol definitions used by each deployment."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    catalog = json.loads((ROOT / "contracts/error-codes.json").read_text())
    for code, messages in catalog.items():
        if not re.fullmatch(r"[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+", code):
            raise SystemExit(f"错误码格式无效：{code}")
        if set(messages) != {"zh-CN", "en"}:
            raise SystemExit(f"错误码缺少语言：{code}")
        params = [set(re.findall(r"\{(\w+)\}", messages[locale])) for locale in ("zh-CN", "en")]
        if params[0] != params[1]:
            raise SystemExit(f"错误码插值参数不一致：{code}")
    codes = sorted(catalog)
    python = '"""Generated by scripts/generate-contracts.py; edit contracts/error-codes.json."""\n\nfrom __future__ import annotations\n\nfrom typing import Dict, Literal\n\n'
    python += "ErrorCode = Literal[\n" + "".join(f"    {code!r},\n" for code in codes) + "]\n\n"
    python += "ERROR_TITLES: Dict[str, str] = " + repr({c: catalog[c]["zh-CN"] for c in codes}) + "\n"
    models = (ROOT / "contracts/models.py").read_text()
    outputs = {}
    for package in ("app/core", "agent"):
        outputs[f"{package}/error_codes.py"] = python
        outputs[f"{package}/contracts.py"] = models
        outputs[f"{package}/contract_openapi.py"] = (ROOT / "contracts/openapi.py").read_text()
    outputs["frontend/src/types/errorCodes.ts"] = (
        "// Generated by scripts/generate-contracts.py.\nexport const errorCodes = "
        + json.dumps(codes, ensure_ascii=False, indent=2) + " as const\nexport type ErrorCode = typeof errorCodes[number]\n"
    )
    for locale in ("zh-CN", "en"):
        path = f"frontend/src/i18n/locales/{locale}/common.json"
        data = json.loads((ROOT / path).read_text())
        errors: dict = {}
        for code in codes:
            current = errors
            *parents, leaf = code.split(".")
            for part in parents:
                current = current.setdefault(part, {})
            current[leaf] = catalog[code][locale]
        data["apiErrors"] = errors
        outputs[path] = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    stale = []
    for name, content in outputs.items():
        path = ROOT / name
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        raise SystemExit("契约生成物未更新：\n" + "\n".join(stale))
    print(f"{'检查' if check else '生成'}完成：{len(codes)} 个错误码，{len(outputs)} 个文件")


if __name__ == "__main__":
    main()
